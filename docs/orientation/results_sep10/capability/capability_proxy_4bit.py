"""The external capability proxy re-run on worker A's fixed 4-bit ladder (item 4).

Item 4 (branch altj-sep10-revisions, commit 8e02ed5) found the inverse truth-regime
relationship loses significance at fixed 4-bit. capability_proxy.py used the mixed-
quantization ladder, so its result is re-run here on the 4-bit scores.

Inputs: A's committed per-claim files `{matched4b,disjoint4b}_<model>.jsonl`, extracted
read-only with `git show altj-sep10-revisions:data/prep/predictions_7b/<file>` into
--pred-dir (A's working tree is not read or written). Proxies: proxies.json.

Check first: the OLS slope of regime on truth must reproduce A's item4_inverse.json
(matched4b -0.571, disjoint4b -0.268 on all nine).

    python3 docs/orientation/results_sep10/capability/capability_proxy_4bit.py --pred-dir <dir>
"""
import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy import stats

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "docs/orientation/results_sep10/inverse"))
from inverse_truth import ADMITTED, ARMS, auroc, exact_perm_p, load, ols  # noqa: E402

OUT = Path(__file__).resolve().parent
A_SLOPES = {"matched4b": -0.571, "disjoint4b": -0.268}  # item4_inverse.json / README, all nine


def per_model(pred, prefix):
    out = {}
    for m in ADMITTED:
        d = load(pred / f"{prefix}_{m}.jsonl")
        S = np.array([[d[e][a] for a in ARMS] for e in sorted(d)])
        T, F, V = S[:, 0], S[:, 1], S[:, 2]
        out[m] = {"truth": auroc(T, F), "regime": auroc(T, V), "regime_paired_win": float(np.mean(T > V))}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pred-dir", required=True)
    args = ap.parse_args()
    pred = Path(args.pred_dir)
    prox = json.load(open(OUT / "proxies.json"))["proxies"]
    models = list(ADMITTED)
    fam = {m: ADMITTED[m][1] for m in models}
    res = {"source": "altj-sep10-revisions @ 9829f89, data/prep/predictions_7b/{matched4b,disjoint4b}_*.jsonl", "sets": {}}
    L = ["# External capability proxy on the fixed 4-bit ladder (generated by capability_proxy_4bit.py)", "",
         "Scores: worker A item 4 (4-bit affine g64; gpt-oss MXFP4-Q4, `--bos off`). Exact permutation p over all orderings.", ""]
    for prefix in ("matched4b", "disjoint4b"):
        pm = per_model(pred, prefix)
        x_t = np.array([pm[m]["truth"] for m in models])
        y = np.array([pm[m]["regime"] for m in models])
        b_check = float(ols(x_t, y)[0][1])
        entry = {"per_model": pm, "check_slope_truth": b_check, "a_reported": A_SLOPES[prefix],
                 "check_ok": abs(b_check - A_SLOPES[prefix]) < 0.0015, "fits": {}}
        xs = {"truth AUROC (in-instrument)": {m: pm[m]["truth"] for m in models}}
        for k, spec in prox.items():
            xs[k] = {m: (None if spec["values"].get(m, {}).get("value") is None else
                         (math.log10(spec["values"][m]["value"]) if spec.get("log10") else spec["values"][m]["value"]))
                     for m in models}
        L += [f"## {prefix} (slope on truth {b_check:+.3f}; A reported {A_SLOPES[prefix]:+.3f}: "
              f"{'reproduces' if entry['check_ok'] else 'DOES NOT reproduce'})", "",
              "| x | outcome | n | slope | Spearman ρ | permutation p | without gemma / without gpt-oss |", "|---|---|---|---|---|---|---|"]
        for k, xv in xs.items():
            ms = [m for m in models if xv[m] is not None]
            for oname in ("regime", "regime_paired_win"):
                x = np.array([xv[m] for m in ms], float)
                yy = np.array([pm[m][oname] for m in ms], float)
                f = {"n": len(ms), "slope": float(ols(x, yy)[0][1]), "spearman": float(stats.spearmanr(x, yy)[0]),
                     "perm_p": exact_perm_p(x, yy)}
                lofo = {}
                for fm in ("gemma", "gpt-oss"):
                    keep = [i for i, m in enumerate(ms) if fam[m] != fm]
                    if len(keep) >= 4 and len(keep) < len(ms):
                        lofo[fm] = float(stats.spearmanr(x[keep], yy[keep])[0])
                f["lofo_spearman"] = lofo
                entry["fits"][f"{k} | {oname}"] = f
                lo = " / ".join(f"{v:+.3f}" for v in lofo.values())
                L.append(f"| {k} | {oname} | {f['n']} | {f['slope']:+.4f} | {f['spearman']:+.3f} | {f['perm_p']:.4f} | ρ {lo} |")
        L.append("")
        res["sets"][prefix] = entry
    json.dump(res, open(OUT / "capability_proxy_4bit.json", "w"), indent=1)
    (OUT / "capability_proxy_4bit.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
