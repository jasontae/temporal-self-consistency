"""Directive 3 (worker B): an external capability proxy for the inverse result.

Fused-critique attack 3: truth AUROC is measured by the same instrument as regime
AUROC, so "regime separation falls as truth discrimination rises" could be an
in-instrument artifact. Here the x-axis is replaced by proxies measured outside the
instrument: parameter count (total; active for MoE) and a published benchmark score
where verifiable (`proxies.json`, each value with its source URL).

For each proxy: OLS slope of regime AUROC on the proxy, Spearman rho, exact
permutation p (all 9! orderings, via inverse_truth.exact_perm_p), and
leave-one-family-out. The paired regime win rate is reported as a second outcome.
Models: the nine admitted.

    python3 docs/orientation/results_sep10/capability/capability_proxy.py
"""
import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy import stats

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "docs/orientation/results_sep10/inverse"))
from inverse_truth import ADMITTED, exact_perm_p, ols  # noqa: E402

OUT = Path(__file__).resolve().parent


def fit(x, y):
    b = float(ols(x, y)[0][1])
    rho, _ = stats.spearmanr(x, y)
    return {"n": int(len(x)), "slope": b, "spearman": float(rho), "perm_p": exact_perm_p(x, y)}


def main():
    per = json.load(open(ROOT / "docs/orientation/results_sep10/inverse/inverse_matched.json"))["per_model"]
    prox = json.load(open(OUT / "proxies.json"))
    models = list(ADMITTED)
    fam = {m: ADMITTED[m][1] for m in models}
    res = {"models": models, "proxies": {}}
    outcomes = {"regime AUROC": {m: per[m]["regime"] for m in models},
                "regime paired win": {m: per[m]["regime_paired_win"] for m in models}}
    xs = {"truth AUROC (in-instrument, reference)": {m: per[m]["truth"] for m in models}}
    for key, spec in prox["proxies"].items():
        vals = {m: spec["values"].get(m, {}).get("value") for m in models}
        xs[key] = {m: (math.log10(v) if spec.get("log10") and v is not None else v) for m, v in vals.items()}
    for key, xv in xs.items():
        ms = [m for m in models if xv.get(m) is not None]
        entry = {"available_for": ms}
        for oname, ov in outcomes.items():
            x = np.array([xv[m] for m in ms], float)
            y = np.array([ov[m] for m in ms], float)
            if len(ms) < 5 or np.ptp(x) == 0:
                entry[oname] = {"n": len(ms), "note": "too few models"}
                continue
            e = fit(x, y)
            lofo = {}
            for f in sorted(set(fam[m] for m in ms)):
                keep = [i for i, m in enumerate(ms) if fam[m] != f]
                if len(keep) >= 4 and np.ptp(x[keep]) > 0:
                    lofo[f"without {f}"] = {"n": len(keep), "slope": float(ols(x[keep], y[keep])[0][1]),
                                            "spearman": float(stats.spearmanr(x[keep], y[keep])[0])}
            e["leave_one_family_out"] = lofo
            entry[oname] = e
        res["proxies"][key] = entry
    # correlation between proxies and truth AUROC (is the proxy measuring what truth AUROC measures?)
    res["proxy_vs_truth_spearman"] = {
        k: float(stats.spearmanr([xs[k][m] for m in models if xs[k].get(m) is not None],
                                 [per[m]["truth"] for m in models if xs[k].get(m) is not None])[0])
        for k in xs if sum(xs[k].get(m) is not None for m in models) >= 5}
    json.dump(res, open(OUT / "capability_proxy.json", "w"), indent=1)

    L = ["# External capability proxy for the inverse result (generated by capability_proxy.py)", "",
         "Outcome: regime AUROC (and paired win rate) of the nine admitted models. Exact permutation p over all orderings.", "",
         "| x | outcome | n | slope | Spearman ρ | permutation p | leave-one-family-out slopes |", "|---|---|---|---|---|---|---|"]
    for k, e in res["proxies"].items():
        for o in outcomes:
            v = e[o]
            if "slope" not in v:
                L.append(f"| {k} | {o} | {v['n']} | — | — | — | too few models |")
                continue
            lofo = "; ".join(f"{kk}: {vv['slope']:+.3f} (n {vv['n']})" for kk, vv in v["leave_one_family_out"].items())
            L.append(f"| {k} | {o} | {v['n']} | {v['slope']:+.4f} | {v['spearman']:+.3f} | {v['perm_p']:.4f} | {lofo} |")
    L += ["", "Spearman of each proxy with truth AUROC: " +
          "; ".join(f"{k}: {v:+.3f}" for k, v in res["proxy_vs_truth_spearman"].items()), "",
          "Sources for every proxy value: `proxies.json`."]
    (OUT / "capability_proxy.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
